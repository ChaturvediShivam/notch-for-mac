import AppKit

struct ClipItem: Identifiable, Codable, Equatable {
    var id = UUID()
    var text: String
    var date = Date()
    var pinned = false
}

/// Text clipboard history. Polls changeCount (an integer read, ~free) twice a second.
/// Skips items password managers mark as concealed/transient.
@MainActor
final class ClipboardService: ObservableObject {
    static let shared = ClipboardService()

    @Published private(set) var items: [ClipItem] = DataFile.load("clipboard.json", as: [ClipItem].self) ?? []
    @Published var paused = false
    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    private static let skip: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                            "com.agilebits.onepassword", "org.nspasteboard.AutoGeneratedType"]

    private init() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardService.shared.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard !paused, let types = pb.types, !types.contains(where: { Self.skip.contains($0.rawValue) }) else { return }
        var text = pb.string(forType: .string)
        if text == nil, let urls = pb.readObjects(forClasses: [NSURL.self]) as? [URL], !urls.isEmpty {
            text = urls.map { $0.isFileURL ? $0.path : $0.absoluteString }.joined(separator: "\n")
        }
        guard let t = text, !t.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let wasPinned = items.first { $0.text == t }?.pinned ?? false
        items.removeAll { $0.text == t }
        items.insert(ClipItem(text: t, pinned: wasPinned), at: 0)
        trim(); save()
    }

    private func trim() {
        let limit = Store.shared.config.clipboardLimit
        var unpinned = 0
        items = items.filter { $0.pinned || { unpinned += 1; return unpinned <= limit }() }
    }

    private func save() { DataFile.save("clipboard.json", items) }

    func copy(_ i: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents(); pb.setString(i.text, forType: .string)
    }

    /// Copy and paste into the app in front (needs Accessibility; otherwise just copies).
    func paste(_ i: ClipItem) {
        NotchModel.shared.setOpen(false)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) { VoiceService.paste(i.text) }
    }

    func togglePin(_ i: ClipItem) {
        guard let k = items.firstIndex(of: i) else { return }
        items[k].pinned.toggle(); save()
    }

    func remove(_ i: ClipItem) { items.removeAll { $0.id == i.id }; save() }
    func clear() { items.removeAll { !$0.pinned }; save() }
}
